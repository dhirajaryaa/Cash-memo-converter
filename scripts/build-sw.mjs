// After `next build`, write a service worker that precaches the exported app
// shell. public/sw.js stays as the small runtime fallback for other hosts.
import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "out");

if (!existsSync(outDir)) {
  console.log("out/ not found; skipping service worker generation.");
  process.exit(0);
}

const included = /\.(?:html|js|mjs|css|svg|png|ico|webmanifest|woff2?|ttf)$/i;

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : [full];
  });
}

const files = walk(outDir)
  .filter((file) => included.test(file) && !file.endsWith(`${sep}sw.js`))
  .sort();

const hash = createHash("sha256");
for (const file of files) hash.update(readFileSync(file));
const version = hash.digest("hex").slice(0, 10);

const urls = [
  "/",
  ...files.map((file) => "/" + relative(outDir, file).split(sep).map(encodeURIComponent).join("/")),
];
const precache = [...new Set(urls)];

const worker = `/* Generated by scripts/build-sw.mjs. Precaches the exported app shell. */
const CACHE = "delivery-list-${version}";
const PRECACHE = ${JSON.stringify(precache, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      await Promise.all(
        PRECACHE.map(async (url) => {
          try {
            const response = await fetch(url, { cache: "reload" });
            if (response.ok) await cache.put(url, response);
          } catch {
            // A missing asset must not block the installed app.
          }
        }),
      );
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key)));
      await self.clients.claim();
    })(),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === "navigate") {
    event.respondWith(
      (async () => {
        try {
          const response = await fetch(request);
          if (response.ok) {
            const cache = await caches.open(CACHE);
            await cache.put(request, response.clone());
          }
          return response;
        } catch {
          return (await caches.match(request)) || (await caches.match("/")) || Response.error();
        }
      })(),
    );
    return;
  }

  event.respondWith(
    (async () => {
      const hit = await caches.match(request);
      if (hit) return hit;
      try {
        const response = await fetch(request);
        if (response.ok) {
          const cache = await caches.open(CACHE);
          await cache.put(request, response.clone());
        }
        return response;
      } catch {
        return Response.error();
      }
    })(),
  );
});
`;

writeFileSync(join(outDir, "sw.js"), worker);
console.log(`out/sw.js written: ${precache.length} precached URLs, cache ${version}`);
